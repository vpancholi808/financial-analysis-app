"""Presentation helpers: number formatting, plain-English metric labels, grades.

Display-only. Nothing here changes a model calculation. Inputs come from
finance_models / advanced_models / research_workbench outputs. Missing values
are always shown as MISSING ("—"), never as zero.
"""
from __future__ import annotations

import math
from dataclasses import dataclass

MISSING = "—"

# One meaning per color, used everywhere (badges, table text, chart marks).
GOOD, CAUTION, BAD, NEUTRAL, NA = "good", "caution", "bad", "neutral", "na"
TONE_HEX = {  # mid-tone steps chosen to clear ~3:1 on both light and dark surfaces
    GOOD: "#1E9E5A", CAUTION: "#C98500", BAD: "#D64545",
    NEUTRAL: "#7B8794", NA: "#8A94A0",
}
TONE_BADGE = {GOOD: "green", CAUTION: "orange", BAD: "red", NEUTRAL: "gray", NA: "gray"}
ICONS = {"strong": "▲", "neutral": "●", "weak": "▼", "flag": "⚠", "clear": "✓", "na": "–"}


def num(x) -> float:
    """Coerce to a finite float, else NaN (never 0)."""
    try:
        v = float(x)
    except (TypeError, ValueError):
        return math.nan
    return v if math.isfinite(v) else math.nan


def is_missing(x) -> bool:
    return not math.isfinite(num(x))


# ---------------------------------------------------------------- numbers
def fmt_money(x, currency: str = "USD") -> str:
    """$49.8B, $950M, $1.25T, -$3.2B. Missing -> '—'."""
    v = num(x)
    if math.isnan(v):
        return MISSING
    a = abs(v)
    if a >= 1e12:
        body = f"{a / 1e12:,.2f}T"
    elif a >= 1e9:
        body = f"{a / 1e9:,.1f}B"
    elif a >= 1e6:
        body = f"{a / 1e6:,.0f}M"
    elif a >= 1e3:
        body = f"{a / 1e3:,.0f}K"
    else:
        body = f"{a:,.0f}"
    prefix = "$" if (currency or "USD").upper() == "USD" else f"{currency} "
    return ("-" if v < 0 else "") + prefix + body


def fmt_pct(x, decimals: int = 1, signed: bool = False) -> str:
    """Fraction -> percent text: 0.286 -> '28.6%'. signed adds an explicit '+'."""
    v = num(x)
    if math.isnan(v):
        return MISSING
    return f"{100 * v:{'+' if signed else ''},.{decimals}f}%"


def fmt_multiple(x, decimals: int = 1) -> str:
    v = num(x)
    return MISSING if math.isnan(v) else f"{v:,.{decimals}f}×"


def fmt_number(x, decimals: int = 2, signed: bool = False) -> str:
    v = num(x)
    return MISSING if math.isnan(v) else f"{v:{'+' if signed else ''},.{decimals}f}"


def ordinal(x) -> str:
    """73.4 -> '73rd'. Percentiles are rounded to whole numbers."""
    v = num(x)
    if math.isnan(v):
        return MISSING
    n = int(round(v))
    suffix = "th" if 10 <= n % 100 <= 20 else {1: "st", 2: "nd", 3: "rd"}.get(n % 10, "th")
    return f"{n}{suffix}"


# ---------------------------------------------------------------- metrics
@dataclass(frozen=True)
class MetricInfo:
    key: str
    name: str            # plain English
    acronym: str         # course acronym, shown second
    kind: str            # pct | ratio | score
    higher_is_better: bool
    help: str            # one sentence: what it measures
    formula: str

    @property
    def label(self) -> str:
        return f"{self.name} ({self.acronym})" if self.acronym else self.name

    @property
    def direction(self) -> str:
        return "Higher is better" if self.higher_is_better else "Lower is better"

    @property
    def tooltip(self) -> str:
        return f"{self.help} {self.direction}. Formula: {self.formula}."


